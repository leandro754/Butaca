CREATE TABLE IF NOT EXISTS entrada (
	-- Identificador interno del ticket.
	id_entrada BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	-- Codigo que identifica el ticket y se utiliza para validarlo.
	codigo_unico_entrada UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
	id_evento BIGINT NOT NULL,
	-- Tarifa aplicada. Nulo en entradas historicas; la aplicacion debe validar que el tipo pertenezca al mismo evento.
	id_tipo_entrada BIGINT,
	-- Persona titular que utilizara la entrada.
	id_persona_titular BIGINT NOT NULL,
	-- Puede ser nulo para una entrada de cortesia.
	id_compra BIGINT,
	estado_entrada estado_entrada NOT NULL DEFAULT 'CONFIRMADA',
	-- Precio historico al momento de emitir el ticket.
	precio_pagado_entrada NUMERIC(12,2) NOT NULL CHECK (precio_pagado_entrada >= 0),
	-- Moneda del precio pagado; se congela junto con el precio historico.
	moneda_entrada CHAR(3) NOT NULL DEFAULT 'ARS',
	fecha_emision_entrada TIMESTAMP NOT NULL DEFAULT now(),
	-- Momento del primer uso; nulo mientras no fue utilizada.
	fecha_validacion_entrada TIMESTAMP CHECK (((estado_entrada = 'USADA' AND fecha_validacion_entrada IS NOT NULL) OR (estado_entrada <> 'USADA' AND fecha_validacion_entrada IS NULL))),
	-- Version para control de concurrencia optimista (@Version) al validar o anular el ticket.
	version_entrada BIGINT NOT NULL DEFAULT 0,
	created_at TIMESTAMP NOT NULL DEFAULT now(),
	-- Se actualiza en cada UPDATE desde la aplicación o un trigger.
	updated_at TIMESTAMP DEFAULT now(),
	PRIMARY KEY (id_entrada)
);
