-- ============================================================================
-- PROYECTO BUTACA - ESQUEMA RELACIONAL NORMALIZADO (1FN, 2FN, 3FN, FNBC)
-- Seguridad Informática: minimización de datos inspirada en PCI-DSS, KYC
-- (Ley 25.326), SHA-256, bloqueo optimista (@Version), entrada nominal y
-- auditoría. La integración KYC/pago del código es simulada: este esquema no
-- implica certificación PCI-DSS ni conexión real con RENAPER.
-- Total: 13 Tablas
-- ============================================================================

CREATE TABLE rol (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario VARCHAR(80) NOT NULL,
    apellido_usuario VARCHAR(80) NOT NULL,
    email_usuario VARCHAR(120) NOT NULL UNIQUE,
    dni_usuario VARCHAR(15) UNIQUE,
    password_usuario VARCHAR(120) NOT NULL,
    telefono_usuario VARCHAR(30),
    estado_usuario VARCHAR(20) NOT NULL,
    fecha_creacion_usuario TIMESTAMP NOT NULL,
    id_rol BIGINT NOT NULL,
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES rol(id_rol)
);

CREATE TABLE verificacion_identidad (
    id_verificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL UNIQUE,
    metodo_verificacion VARCHAR(30) NOT NULL,
    estado_verificacion VARCHAR(20) NOT NULL,
    codigo_validacion_kyc VARCHAR(80) NOT NULL UNIQUE,
    observacion_verificacion VARCHAR(250),
    hash_evidencia_documental VARCHAR(64),
    hash_selfie VARCHAR(64),
    proveedor_identidad VARCHAR(60),
    puntaje_coincidencia DECIMAL(5, 4),
    fecha_solicitud TIMESTAMP NOT NULL,
    fecha_verificacion TIMESTAMP,
    CONSTRAINT fk_verificacion_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario)
);

CREATE TABLE ubicacion (
    id_ubicacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_ubicacion VARCHAR(120) NOT NULL UNIQUE,
    direccion_ubicacion VARCHAR(180) NOT NULL,
    capacidad_maxima_ubicacion INT NOT NULL CHECK (capacidad_maxima_ubicacion > 0),
    activa_ubicacion BOOLEAN NOT NULL
);

CREATE TABLE categoria (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR(80) NOT NULL UNIQUE,
    descripcion_categoria VARCHAR(200) NOT NULL
);

CREATE TABLE evento (
    id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo_evento VARCHAR(120) NOT NULL,
    descripcion_evento VARCHAR(1200) NOT NULL,
    fecha_inicio_evento TIMESTAMP NOT NULL,
    precio_actual_evento DECIMAL(10, 2) NOT NULL CHECK (precio_actual_evento >= 0),
    cupo_total_evento INT NOT NULL CHECK (cupo_total_evento > 0),
    estado_evento VARCHAR(20) NOT NULL,
    imagen_url_evento VARCHAR(300) NOT NULL,
    fecha_creacion_evento TIMESTAMP NOT NULL,
    version_evento BIGINT NOT NULL DEFAULT 0,
    id_organizador BIGINT NOT NULL,
    id_categoria BIGINT NOT NULL,
    id_ubicacion BIGINT NOT NULL,
    CONSTRAINT fk_evento_organizador FOREIGN KEY (id_organizador) REFERENCES usuario(id_usuario),
    CONSTRAINT fk_evento_categoria FOREIGN KEY (id_categoria) REFERENCES categoria(id_categoria),
    CONSTRAINT fk_evento_ubicacion FOREIGN KEY (id_ubicacion) REFERENCES ubicacion(id_ubicacion)
);

CREATE TABLE compra (
    id_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL,
    fecha_compra TIMESTAMP NOT NULL,
    estado_compra VARCHAR(20) NOT NULL,
    CONSTRAINT fk_compra_cliente FOREIGN KEY (id_cliente) REFERENCES usuario(id_usuario)
);

CREATE TABLE pago (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra BIGINT NOT NULL UNIQUE,
    pasarela_pago VARCHAR(30) NOT NULL,
    medio_pago VARCHAR(30) NOT NULL,
    estado_pago VARCHAR(20) NOT NULL,
    referencia_externa_pago VARCHAR(80) NOT NULL UNIQUE,
    ultimos_cuatro_digitos VARCHAR(4) NOT NULL,
    monto_pago DECIMAL(10, 2),
    moneda_pago VARCHAR(3) DEFAULT 'ARS',
    codigo_autorizacion_pago VARCHAR(50),
    fecha_pago TIMESTAMP NOT NULL,
    CONSTRAINT fk_pago_compra FOREIGN KEY (id_compra) REFERENCES compra(id_compra)
);

CREATE TABLE comprobante (
    id_comprobante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra BIGINT NOT NULL UNIQUE,
    numero_comprobante VARCHAR(40) NOT NULL UNIQUE,
    tipo_comprobante VARCHAR(25) NOT NULL,
    hash_cruce_seguridad VARCHAR(64) NOT NULL UNIQUE,
    estado_envio_entrada VARCHAR(20) NOT NULL,
    fecha_emision_comprobante TIMESTAMP NOT NULL,
    CONSTRAINT fk_comprobante_compra FOREIGN KEY (id_compra) REFERENCES compra(id_compra)
);

CREATE TABLE entrada (
    id_entrada BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_unico_entrada VARCHAR(36) NOT NULL UNIQUE,
    estado_entrada VARCHAR(20) NOT NULL,
    precio_pagado_entrada DECIMAL(10, 2) NOT NULL,
    dni_asistente_entrada VARCHAR(15) NOT NULL,
    nombre_asistente_entrada VARCHAR(120) NOT NULL,
    fecha_emision_entrada TIMESTAMP NOT NULL,
    id_evento BIGINT NOT NULL,
    id_compra BIGINT NOT NULL,
    CONSTRAINT fk_entrada_evento FOREIGN KEY (id_evento) REFERENCES evento(id_evento),
    CONSTRAINT fk_entrada_compra FOREIGN KEY (id_compra) REFERENCES compra(id_compra)
);

CREATE TABLE historial_estado_entrada (
    id_historial_estado_entrada BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_entrada BIGINT NOT NULL,
    estado_anterior_entrada VARCHAR(20),
    estado_nuevo_entrada VARCHAR(20) NOT NULL,
    fecha_cambio_entrada TIMESTAMP NOT NULL,
    motivo_cambio_entrada VARCHAR(160) NOT NULL,
    CONSTRAINT fk_historial_entrada FOREIGN KEY (id_entrada) REFERENCES entrada(id_entrada)
);

CREATE TABLE notificacion (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_destino BIGINT NOT NULL,
    id_evento_relacionado BIGINT,
    tipo_notificacion VARCHAR(30) NOT NULL,
    mensaje_notificacion VARCHAR(500) NOT NULL,
    leida_notificacion BOOLEAN NOT NULL,
    fecha_creacion_notificacion TIMESTAMP NOT NULL,
    CONSTRAINT fk_notificacion_usuario FOREIGN KEY (id_usuario_destino) REFERENCES usuario(id_usuario),
    CONSTRAINT fk_notificacion_evento FOREIGN KEY (id_evento_relacionado) REFERENCES evento(id_evento)
);

CREATE TABLE auditoria_seguridad (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT,
    accion_auditoria VARCHAR(50) NOT NULL,
    entidad_afectada VARCHAR(50) NOT NULL,
    id_registro_afectado VARCHAR(60) NOT NULL,
    resultado_operacion VARCHAR(20) NOT NULL,
    ip_origen VARCHAR(45) NOT NULL,
    detalle_cruce VARCHAR(350) NOT NULL,
    fecha_evento_auditoria TIMESTAMP NOT NULL,
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario)
);
